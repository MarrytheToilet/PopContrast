"""Build the finite-history-bank sensitivity table from frozen records.

No fitting, resampling, or test-driven selection is performed. M=32 is a fixed
reporting budget; the manifest retains every recorded M and validation rule.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from statistics import mean, stdev

from .sources import source_path

ROOT = Path(__file__).resolve().parents[2]
DATASETS = [("beauty", "Beauty"), ("clothing", "Clothing"), ("ml1m", "MovieLens-1M"),
            ("sports", "Sports"), ("toys", "Toys")]
RULE = "budget_5pct"
SIZE = 32


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "results/tables")
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    sources, displayed, rows, all_sizes = {}, [], [], {}
    for dataset, name in DATASETS:
        folder = ROOT / "results/benchmark/estimator_resampling" / dataset
        paths = [folder / "results.json", folder / "config.json"]
        results, config = [json.loads(source_path(p).read_text()) for p in paths]
        sources.update({str(p.relative_to(ROOT)): hashlib.sha256(source_path(p).read_bytes()).hexdigest()
                        for p in paths})
        draws = [r for r in results["draws"] if r["M"] == SIZE]
        assert len(draws) == config["repetitions"] == 20
        row, values = [name] + [f"{100 * results['raw_test'][k]:.3f}"
                               for k in ["R10", "tailR10"]], {}
        for family in ["geometric", "arithmetic"]:
            chosen = [r["selected_test"][family][RULE]["test"] for r in draws]
            summary = next(s for s in results["summary"] if s["M"] == SIZE
                           and s["family"] == family and s["rule"] == RULE)
            values[family] = {}
            for metric in ["R10", "tailR10"]:
                x = [100 * r[metric] for r in chosen]
                average, deviation = mean(x), stdev(x)
                assert abs(average - 100 * summary[metric]["mean"]) < 1e-10
                assert abs(deviation - 100 * summary[metric]["sd"]) < 1e-10
                values[family][metric] = {"mean_percent": average, "sd_pp": deviation}
                row.append(rf"{average:.3f}$\pm${deviation:.3f}")
        null = results["null_test"]["null"][RULE]["test"]
        row.extend(f"{100 * null[k]:.3f}" for k in ["R10", "tailR10"])
        displayed.append(dict(dataset=dataset, M=SIZE, draws=20, rule=RULE,
                              raw_percent={k: 100 * results["raw_test"][k] for k in ["R10", "tailR10"]},
                              values=values, null_percent={k: 100 * null[k] for k in ["R10", "tailR10"]},
                              scope=config["scope"]))
        all_sizes[dataset] = results["summary"]
        rows.append(" & ".join(row) + r" \\")
    output = args.output_dir / "estimator_stability.tex"
    output.write_text("% Generated by experiments.figures.estimator_stability; do not edit numbers.\n"
                      + "\n".join(rows) + "\n")
    manifest = dict(sources=sources, displayed=displayed, all_recorded_summaries=all_sizes,
                    interpretation="Finite-bank subset sensitivity including validation selection; "
                    "not independent training variability, population uncertainty, or a paired "
                    "significance test between estimator families.",
                    output_sha256=hashlib.sha256(output.read_bytes()).hexdigest())
    (args.output_dir / "estimator_stability_sources.json").write_text(
        json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(dict(table=str(output), datasets=len(rows), M=SIZE, draws=20,
                          selected_test_values_recomputed=True)))


if __name__ == "__main__":
    main()

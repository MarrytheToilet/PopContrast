ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__import__("os").environ.get("POPCONTRAST_PUBLICATION_DIR", ROOT / "results"))
BASE = ROOT / 'results/benchmark'
OUT = HERE / 'tables'
OUT.mkdir(exist_ok=True, parents=True)
SOURCES = {}

def read(path):
    path = Path(path)
    actual = source_path(path)
    SOURCES[str(path.relative_to(ROOT))] = hashlib.sha256(actual.read_bytes()).hexdigest()
    return json.loads(actual.read_text())

def csvread(path):
    path = Path(path)
    actual = source_path(path)
    SOURCES[str(path.relative_to(ROOT))] = hashlib.sha256(actual.read_bytes()).hexdigest()
    return list(csv.DictReader(actual.open()))

def write(name, lines):
    (OUT / (name + '.tex')).write_text('% Generated by build_assets.py; do not edit numbers.\n' + '\n'.join(lines) + '\n')

def pct(x, n=2):
    return f'{100*x:.{n}f}'

def change(b, r, key):
    return rf'{pct(b[key])}$\to${pct(r[key])}'

def interval(x):
    # Retain a small signed bound if two-decimal rounding would hide its sign.
    return '[' + ', '.join(pct(v, 4 if 0 < abs(100*v) < .005 else 2) for v in x) + ']'

def beta(row):
    return row['method'].split(':')[-1] if row['method'] != 'raw' else '0'


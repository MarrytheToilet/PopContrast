def shortlabel(run,r):
    if run.startswith('lcrec_qwen1'): return 'Qwen1.5B'
    if run.startswith('lcrec_qwen3'): return 'Qwen3B'
    if run.startswith('lcrec_smol'): return 'Smol360M'
    if run.startswith('legacy'): return 'TIGER legacy'
    if r['model']=='TIGER':
        return 'TIGER'+(' (padded)' if not r.get('length_grouping') else '')
    return {'sasrec':'SASRec-CE','hstu':'HSTU-NT'}[r['model']]

